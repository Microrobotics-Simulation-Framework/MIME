"""The profiles, and the two tables they act by: the classes of finding (each code's class, each class with what covers
it) and the profile rules ((profile, class) to an action). The code that applies them reads a finding's class and the
rule for it, never a code, so a1 adds classes and rows as data.

Profiles act on waivers alone: a rule that covers a finding does so with a waiver, generated with a pending basis or
the experiment's own with a basis, and nothing else. :func:`waivers_alone` holds every row to it, and a test plants a
rule that generates something else."""

from __future__ import annotations

from collections.abc import Callable, Generator, Mapping, Sequence
from contextlib import contextmanager
from dataclasses import dataclass, field
from enum import Enum
from importlib.resources import files
from types import MappingProxyType

from mime.validity._bases import PENDING, Basis, basis_text


class Profile(Enum):
    """How much a build asks of an experiment. ``exploratory`` (the default): what an experiment leaves unstated is
    waived with a pending reason, recorded and stamped on every output, so a first run needs no paperwork; validity
    limits and input errors are refused as in every profile. ``research``: each of those needs its reason, and a
    pending one is refused by name. ``strict`` holds a higher evidence standard, and confers nothing; it is a1's, and
    refused in dev1."""

    EXPLORATORY = "exploratory"
    RESEARCH = "research"
    STRICT = "strict"


#: The profiles dev1 builds.
BUILT = (Profile.EXPLORATORY, Profile.RESEARCH)
DEFAULT_PROFILE = Profile.EXPLORATORY


def profile_of(value: object) -> tuple[Profile | None, tuple[str, str, str] | None]:
    """The profile ``value`` names (``"research"`` or ``Profile.RESEARCH``), or the refusal: a name that is no profile,
    and ``strict``, which a1 builds."""
    held = value.value if isinstance(value, Profile) else value
    found = next((p for p in Profile if p.value == held), None)
    names = ", ".join(repr(p.value) for p in BUILT)
    if found is None:
        return None, ("profile.unknown", f"profile={value!r} is not a profile",
                      f"pass profile= one of {names} (exploratory when not given)")
    if found not in BUILT:
        return None, ("profile.reserved",
                      "the strict profile holds a higher evidence standard, which MIME builds in a1: a strict build "
                      "now could apply only research's rules, and would claim a standard it does not apply",
                      "build with profile=\"research\" until then; strict confers nothing by itself")
    return found, None


class Action(Enum):
    """What a profile does with a finding of a class (profile_rules.txt)."""

    GENERATE = "generate"
    BASIS = "basis"
    LIST = "list"
    REFUSE = "refuse"


class Cover(Enum):
    """What covers a class of finding (design #188's covered-by column)."""

    WAIVER = "waiver"
    SOURCE = "source"
    EVIDENCE = "evidence"
    MODEL_CHANGE = "model_change"
    REQUEST = "request"
    NOTHING = "nothing"


#: What a profile's rule may cover a finding with, by the action: a generated waiver, or the experiment's own waiver
#: or source (one type, so a1's named bases serve both).
_COVERED_BY_ACTION: Mapping[Action, frozenset[Cover]] = MappingProxyType({
    Action.GENERATE: frozenset({Cover.WAIVER}), Action.BASIS: frozenset({Cover.WAIVER, Cover.SOURCE})})


@dataclass(frozen=True)
class Finding:
    """Something a build found that a profile acts on: what it is about, in the experiment's names (``material
    'water' fluid.dynamic_viscosity``, ``drag:umr.spacing``), its code, and what it says in plain words."""

    target: str
    code: str
    text: str


@dataclass(frozen=True)
class Waiver:
    """A finding's waiver: what it waives, the codes it covers, its basis, and whether the profile generated it
    (``generated``) or the experiment declared it. The saved form records each with its basis."""

    target: str
    reasons: tuple[str, ...]
    basis: Basis
    generated: bool = False

    def text(self) -> str:
        how = "generated by the profile" if self.generated else "declared"
        return f"{self.target}: {', '.join(self.reasons)} waived ({how}), basis {basis_text(self.basis)}"


def pending_waiver(finding: Finding) -> Waiver:
    """What a ``generate`` rule makes of a finding: a waiver of it, with a pending basis."""
    return Waiver(finding.target, (finding.code,), PENDING, generated=True)


@dataclass(frozen=True)
class Rule:
    """A profile's rule for a class: its action, and for ``generate`` what it makes of a finding."""

    action: Action
    make: Callable[[Finding], object] = pending_waiver


def _rows(text: str) -> list[tuple[int, list[str]]]:
    return [(number, line.split()) for number, line in enumerate(text.splitlines(), start=1)
            if line.strip() and not line.lstrip().startswith("#")]


@dataclass(frozen=True)
class FindingClasses:
    """Each finding code's class and each class's cover. A code is matched as written (``stated_without_origin``,
    ``condition_unstated:shear_rate``), then by its code alone with ``:*`` (``condition_unstated:*``)."""

    covers: Mapping[str, Cover]
    codes: Mapping[str, str]

    @classmethod
    def read(cls, text: str) -> FindingClasses:
        """The table's rows, ``class  cover  code...``; ``ValueError`` names a line that is not one, a cover that is
        not one of :class:`Cover`, and a class or code on two rows."""
        covers: dict[str, Cover] = {}
        codes: dict[str, str] = {}
        for number, (name, *rest) in _rows(text):
            if not rest:
                raise ValueError(f"line {number}: a class row is the class, what covers it, and its codes")
            if name in covers:
                raise ValueError(f"line {number}: the class {name} has a row already")
            covers[name] = Cover(rest[0])
            for code in rest[1:]:
                if code in codes:
                    raise ValueError(f"line {number}: the code {code} is in the class {codes[code]} already")
                codes[code] = name
        return cls(MappingProxyType(covers), MappingProxyType(codes))

    def class_of(self, code: str) -> str | None:
        if code in self.codes:
            return self.codes[code]
        head, colon, _ = code.partition(":")
        return self.codes.get(f"{head}:*") if colon else None

    def with_class(self, name: str, cover: Cover, codes: Sequence[str]) -> FindingClasses:
        """This table with one more class and its codes, as a1 adds one."""
        return FindingClasses(MappingProxyType({**self.covers, name: cover}),
                              MappingProxyType({**self.codes, **dict.fromkeys(codes, name)}))


@dataclass(frozen=True)
class ProfileRules:
    """The rule for each profile and class; a pair with no rule is nothing."""

    rules: Mapping[tuple[Profile, str], Rule] = field(default_factory=dict[tuple[Profile, str], Rule])

    @classmethod
    def read(cls, text: str) -> ProfileRules:
        """The table's rows, ``profile  class  action``; ``ValueError`` names a line that is not one and a pair on two
        rows."""
        rules: dict[tuple[Profile, str], Rule] = {}
        for number, row in _rows(text):
            if len(row) != 3:
                raise ValueError(f"line {number}: a rule row is a profile, a class and an action")
            key = (Profile(row[0]), row[1])
            if key in rules:
                raise ValueError(f"line {number}: {row[0]} has a rule for {row[1]} already")
            rules[key] = Rule(Action(row[2]))
        return cls(MappingProxyType(rules))

    def rule(self, profile: Profile, cls: str | None) -> Rule | None:
        return None if cls is None else self.rules.get((profile, cls))

    def with_rule(self, profile: Profile, cls: str, rule: Rule) -> ProfileRules:
        """These rules with one more, or one replaced, as a1 adds one (and a test plants one)."""
        return ProfileRules(MappingProxyType({**self.rules, (profile, cls): rule}))


CLASSES_FILE = "finding_classes.txt"
RULES_FILE = "profile_rules.txt"
#: MIME's tables, read from the package.
FINDING_CLASSES = FindingClasses.read(files("mime.validity").joinpath(CLASSES_FILE).read_text(encoding="utf-8"))
PROFILE_RULES = ProfileRules.read(files("mime.validity").joinpath(RULES_FILE).read_text(encoding="utf-8"))


_ACTIVE: list[tuple[FindingClasses, ProfileRules]] = [(FINDING_CLASSES, PROFILE_RULES)]


def active_tables() -> tuple[FindingClasses, ProfileRules]:
    """The tables a build's profile acts by: MIME's, unless :func:`using_tables` holds others."""
    return _ACTIVE[-1]


@contextmanager
def using_tables(classes: FindingClasses, rules: ProfileRules) -> Generator[None]:
    """Build with these tables in place of MIME's while the context is open: how a test adds a class and a row as a1
    will, or plants a rule, with no other edit."""
    _ACTIVE.append((classes, rules))
    try:
        yield
    finally:
        _ACTIVE.pop()


@dataclass(frozen=True)
class Judge:
    """A profile with the tables it acts by: the rule for a finding, read from its class."""

    profile: Profile
    classes: FindingClasses = field(default_factory=lambda: active_tables()[0])
    rules: ProfileRules = field(default_factory=lambda: active_tables()[1])

    def rule(self, code: str) -> Rule | None:
        return self.rules.rule(self.profile, self.classes.class_of(code))

    def action(self, code: str) -> Action | None:
        held = self.rule(code)
        return held.action if held is not None else None


def waivers_alone(classes: FindingClasses, rules: ProfileRules) -> list[str]:
    """Every way a rule covers a finding with something other than a waiver: a ``generate`` or ``basis`` rule on a
    class no waiver covers (a validity limit, an uncovered read), or a ``generate`` rule whose product is not a
    :class:`Waiver` of the finding. Empty when profiles act on waivers alone (design #184 item 1)."""
    found: list[str] = []
    for (profile, name), rule in sorted(rules.rules.items(), key=lambda item: (item[0][0].value, item[0][1])):
        allowed = _COVERED_BY_ACTION.get(rule.action)
        if allowed is None:
            continue
        cover = classes.covers.get(name)
        if cover not in allowed:
            found.append(f"{profile.value} {name}: the rule {rule.action.value}s, and the class is covered by "
                         f"{cover.value if cover is not None else 'no class in the table'}, not by a waiver")
        if rule.action is Action.GENERATE:
            sample = Finding(f"a finding of {name}", next((c for c, held in classes.codes.items() if held == name),
                                                          name), "a planted finding")
            made = rule.make(sample)
            if not (isinstance(made, Waiver) and made.reasons == (sample.code,) and made.generated):
                found.append(f"{profile.value} {name}: the rule generates {type(made).__name__}, not a waiver of "
                             f"the finding")
    return found


