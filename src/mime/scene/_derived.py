"""Derived prims on a stage, and what tells an edited one: a geometry kind's drawn mesh (its ``proxy`` child) and a
region's primitive, each output only, written by MIME from the kind it is derived from and regenerated by every build.
Each carries ``mime:derived_from``, the kind, version and parameters it was derived from (the parameters by the
SHA-256 of their canonical JSON), and ``mime:derived_hash``, the SHA-256 of what it wrote: a mesh's points as USD holds
them (float32, in the stage's units) with its face counts and indices, or a primitive's attributes and transform.

A reader with only the stage recomputes both (:func:`derived_findings`): a derived prim whose content no longer
hashes to what was written was edited, and one whose source's parameters no longer hash to what it records is stale.
A reader with the declarations that wrote the stage compares the stage with the one they write (:func:`stage_edits`),
which also sees an edit that rewrote the recorded hash to match."""

from __future__ import annotations

import hashlib
import json
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any, cast

import numpy as np

from mime.scene._pxr import Sdf, Usd

DERIVED_FROM = "mime:derived_from"
DERIVED_HASH = "mime:derived_hash"
GEOMETRY = "mime:geometry"
GEOMETRY_VERSION = "mime:geometry:version"
#: The ``mime:`` applied schema of a prim that is a geometry kind: written as the ``apiSchemas`` token, with no
#: plugin, as ``MimeMagnetAPI`` is.
GEOMETRY_API = "MimeGeometryAPI"
#: The attributes of a primitive a region prim's hash covers, beside its type, where they are authored.
PRIMITIVE_ATTRIBUTES = ("radius", "height", "axis", "xformOp:translate", "xformOp:orient", "xformOpOrder")

type Parameter = float | list[float]


def canonical(value: object) -> str:
    """``value`` as canonical JSON: sorted keys, no spaces, floats as Python writes them (shortest round trip)."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False)


def sha256_text(text: str) -> str:
    return "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()


def written(value: object) -> Parameter:
    """A setting as the stage holds it: a double, or three."""
    if isinstance(value, (tuple, list)):
        return [float(c) for c in cast(Sequence[float], value)]
    return float(cast(float, value))


def source(kind: str, version: str, parameters: Mapping[str, Parameter], **detail: object) -> str:
    """The ``mime:derived_from`` text of a prim derived from ``kind`` at ``version`` with these written parameters,
    and what else it was derived with (the drawing's segments, the region)."""
    return canonical({"kind": kind, "version": version, "parameters": sha256_text(canonical(dict(parameters))),
                      **detail})


def mesh_hash(points: Any, counts: Sequence[int], indices: Sequence[int]) -> str:
    """The SHA-256 of a mesh as USD holds it: its points as little-endian float32 triples, then its face vertex
    counts and indices as little-endian int32."""
    digest = hashlib.sha256()
    for label, array in (("points", np.asarray(points, dtype="<f4").reshape(-1, 3)),
                         ("counts", np.asarray(counts, dtype="<i4")), ("indices", np.asarray(indices, dtype="<i4"))):
        digest.update(label.encode("ascii"))
        digest.update(array.tobytes())
    return "sha256:" + digest.hexdigest()


def _plain(value: Any) -> Any:
    """An attribute's value as JSON: a string, a number, or a list of them (a quaternion real part first)."""
    if isinstance(value, str):
        return value
    if hasattr(value, "GetReal"):
        return [float(value.GetReal()), *(float(c) for c in value.GetImaginary())]
    try:
        return [_plain(item) for item in value]
    except TypeError:
        return float(value)


def primitive_hash(prim: Any) -> str:
    """The SHA-256 of a primitive prim as composed: its type and the attributes of :data:`PRIMITIVE_ATTRIBUTES` it
    has an authored value for."""
    held: dict[str, object] = {"type": str(prim.GetTypeName())}
    for name in PRIMITIVE_ATTRIBUTES:
        attribute = prim.GetAttribute(name)
        if attribute and attribute.HasAuthoredValue():
            held[name] = _plain(attribute.Get())
    return sha256_text(canonical(held))


def content_hash(prim: Any) -> str:
    """What a derived prim holds now, hashed as it was when written: a mesh's points, counts and indices, or a
    primitive's attributes."""
    if str(prim.GetTypeName()) == "Mesh":
        return mesh_hash(prim.GetAttribute("points").Get() or [], prim.GetAttribute("faceVertexCounts").Get() or [],
                         prim.GetAttribute("faceVertexIndices").Get() or [])
    return primitive_hash(prim)


def kind_parameters(prim: Any) -> dict[str, Parameter]:
    """A kind's prim's parameters as written: every ``mime:geometry:<name>`` attribute but its version."""
    found: dict[str, Parameter] = {}
    for attribute in prim.GetAttributes():
        name = str(attribute.GetName())
        if name.startswith(f"{GEOMETRY}:") and name != GEOMETRY_VERSION and attribute.HasAuthoredValue():
            found[name.removeprefix(f"{GEOMETRY}:")] = cast(Parameter, _plain(attribute.Get()))
    return found


@dataclass(frozen=True)
class DerivedFinding:
    """A derived prim that no longer is what MIME wrote: ``edited`` (its content does not hash to what was written),
    ``stale`` (its source's parameters changed after it was written) or ``unrecorded`` (it carries no hash)."""

    path: str
    finding: str
    message: str


def derived_findings(stage: Any) -> list[DerivedFinding]:
    """Every derived prim on the composed ``stage`` that was edited after it was written, or whose source changed."""
    found: list[DerivedFinding] = []
    for prim in stage.Traverse():
        derived = prim.GetAttribute(DERIVED_FROM)
        if not (derived and derived.HasAuthoredValue()):
            continue
        path = str(prim.GetPath())
        recorded = prim.GetAttribute(DERIVED_HASH)
        if not (recorded and recorded.HasAuthoredValue()):
            found.append(DerivedFinding(path, "unrecorded", f"{path} is derived ({derived.Get()}) and records no "
                                                            f"{DERIVED_HASH}"))
            continue
        now = content_hash(prim)
        if now != recorded.Get():
            found.append(DerivedFinding(path, "edited", f"{path} was edited after it was written: it hashes to {now}, "
                                                        f"and it was written as {recorded.Get()}"))
        parent = prim.GetParent()
        try:
            held: object = json.loads(str(derived.Get()))
        except ValueError:
            held = None
        if not isinstance(held, dict) or parent.GetAttribute(GEOMETRY).Get() is None:
            found.append(DerivedFinding(path, "stale", f"{path} records {DERIVED_FROM} = {derived.Get()!r}, and its "
                                                       f"parent is no geometry kind's prim it could be derived from"))
            continue
        detail = {key: value for key, value in cast(dict[str, object], held).items()
                  if key not in ("kind", "version", "parameters")}
        expected = source(str(parent.GetAttribute(GEOMETRY).Get()), str(parent.GetAttribute(GEOMETRY_VERSION).Get()),
                          kind_parameters(parent), **detail)
        if expected != derived.Get():
            found.append(DerivedFinding(path, "stale", f"{path} was derived from {derived.Get()}, and its source is "
                                                       f"now {expected}: it was not regenerated"))
    return found


def _layer(text: str) -> Any:
    layer = Sdf.Layer.CreateAnonymous(".usda")
    layer.ImportFromString(text)
    return layer


def _derived_paths(layer: Any) -> list[str]:
    stage = Usd.Stage.Open(layer)
    return sorted(str(p.GetPath()) for p in stage.Traverse() if p.GetAttribute(DERIVED_FROM).HasAuthoredValue())


def _without(layer: Any, paths: Sequence[str]) -> str:
    for path in sorted(paths, reverse=True):
        spec = layer.GetPrimAtPath(path)
        if spec:
            parent = spec.nameParent
            parent.RemoveNameChild(spec)
    return str(layer.ExportToString())


def _spec_text(layer: Any, path: str) -> str | None:
    spec = layer.GetPrimAtPath(path)
    if not spec:
        return None
    alone = Sdf.Layer.CreateAnonymous(".usda")
    Sdf.CreatePrimInLayer(alone, path)
    Sdf.CopySpec(layer, path, alone, path)
    return str(alone.ExportToString())


@dataclass(frozen=True)
class StageEdits:
    """How a stage on disk differs from the one its declarations write: ``outside``, whether anything differs beyond
    the derived prims; ``derived``, each derived prim that differs (edited, added or removed)."""

    outside: bool
    derived: tuple[str, ...]


def stage_edits(found: str, wrote: str) -> StageEdits:
    """``found``, a stage's text on disk, against ``wrote``, the text its declarations write: the derived prims are
    the written stage's, so a prim the found stage marks derived is judged as any other, and an edit anywhere but
    the written stage's derived prims (a prim, an attribute or the layer's metadata) is ``outside``."""
    held, written_layer = _layer(found), _layer(wrote)
    derived = _derived_paths(written_layer)
    changed = tuple(path for path in derived if _spec_text(held, path) != _spec_text(written_layer, path))
    outside = _without(_layer(found), derived) != _without(_layer(wrote), derived)
    return StageEdits(outside, changed)


def stage_derived_findings(text: str) -> list[DerivedFinding]:
    """:func:`derived_findings` on a stage held as text."""
    return derived_findings(Usd.Stage.Open(_layer(text)))


